#!/usr/bin/env python3
"""Write scripts/cchamber/run<family>_pool.sh from scripts/cchamber/registration.yaml.

One catalogue per family, 17 candidates x 3 seeds, ordered by seed then candidate id.
The blocks follow the layout parsed by scripts/cluster/lib.sh (extract_cmds). The
launcher supplies ``paths.log_dir``, the root under which each run's ``scores/`` lands
as ``<root>/<run_name>/scores``, and ``data.data_dir``.

``--experiment-group cchamber_wt --suffix _wt_pool`` writes the same blocks for the
wind-tunnel copies of the experiments to run<family>_wt_pool.sh, with the MLflow
experiment ``cchamber_wt_pool``; the run names are unchanged.
"""

import argparse
from pathlib import Path

import yaml

HERE = Path(__file__).parent

# Everything the pool does not need: only score_dump and residual_state (plus the
# harmless model_summary and rich_progress_bar) stay. Hydra in struct mode rejects a
# null on a missing key, so every name must exist in all eight experiments;
# last_epoch_ckpt, clear_ckpts and log_data_mlflow come from callbacks/default.yaml.
NULLED_CALLBACKS = [
    "anomaly_eff",
    "thres_drift",
    "wasserstein_dist",
    "cap_sn_zb",
    "consistency_sn_zb",
    "cap_sn_zb_ema_ckpt",
    "last_epoch_ckpt",
    "clear_ckpts",
    "log_data_mlflow",
]

HEADER = """\
#!/usr/bin/env bash
# ========================================================================
# CAUSAL CHAMBER POOL: {family}, {n_cand} candidates x {n_seed} seeds = {n} runs
# ========================================================================
# Generated by scripts/cchamber/make_pool_catalogue.py from
# scripts/cchamber/registration.yaml. Do not edit by hand: change the registration
# and regenerate.
#
# Every command is commented out and parsed by scripts/cluster/lib.sh, never run
# from this file. The runs only train and dump scores (callbacks.score_dump); the
# launcher passes paths.log_dir (the pool root, so that the scores of a run land in
# <root>/<run_name>/scores), paths.checkpoints_dir and data.data_dir.
"""


def shell_quote(override: str) -> str:
    """Return the override as the catalogues write it: lists single-quoted, strings
    bare."""
    key, value = override.split("=", 1)
    value = value.strip('"')
    return f"{key}='{value}'" if "[" in value else f"{key}={value}"


def block(experiment: str, cand: dict, seed: int, pool: dict, group: str) -> str:
    name = f"{cand['id']}_s{seed}"
    nulls = " ".join(f"callbacks.{c}=null" for c in NULLED_CALLBACKS)
    lines = [
        f"experiment={experiment}",
        f"seed={seed} data.seed=314159 data.batch_size={pool['batch_size']}"
        f" trainer.max_epochs={pool['epochs']}",
        # The experiments set evaluation keys inline, so ~evaluation alone leaves a
        # node with no evaluator target; the two deletions leave it empty.
        "test=false logger=none"
        " ~evaluation ~evaluation.evaluator ~evaluation.callbacks",
        nulls,
        *map(shell_quote, cand["overrides"]),
        f"experiment_name={group}_pool run_name={name}",
        # Single quotes keep ${...} from the shell; Hydra resolves it.
        f"'hydra.run.dir=${{paths.log_dir}}/{name}'",
    ]
    rule = "# " + "-" * 72
    head = [rule, f"# {cand['id']}, seed {seed}", rule]
    body = ["# python3 src/train.py \\"]
    body += [f"#     {line} \\" for line in lines[:-1]] + [f"#     {lines[-1]}"]
    return "\n".join(head + body) + "\n"


def catalogue(family: str, reg: dict, group: str) -> str:
    pool, cands = reg["pool"], reg["pool_candidates"][family]
    # The registration names the light-tunnel experiment; every other group holds a
    # copy of it under the same file name.
    experiment = f"{group}/{Path(reg['families'][family]['experiment']).name}"
    seeds = pool["seeds"]
    head = HEADER.format(
        family=family, n_cand=len(cands), n_seed=len(seeds), n=len(cands) * len(seeds)
    )
    blocks = [block(experiment, c, s, pool, group) for s in seeds for c in cands]
    return head + "\n" + "\n".join(blocks)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--registration", default=HERE / "registration.yaml")
    parser.add_argument("--experiment-group", default="cchamber")
    parser.add_argument("--suffix", default="_pool")
    args = parser.parse_args()
    reg = yaml.safe_load(Path(args.registration).read_text())
    for family in reg["families"]:
        text = catalogue(family, reg, args.experiment_group)
        (HERE / f"run{family}{args.suffix}.sh").write_text(text)


if __name__ == "__main__":
    main()
